"""Regenerate ``_chart_envoy.py`` from the pinned llm-d router chart.

Dev-time only; nothing imports this at runtime. Needs ``helm`` (v3.19.0 used)
and network access to ghcr.io:

    python src/providers/k8s/llmd/_regenerate.py

It renders the chart with ``helm template`` and vendors the Envoy sidecar's
config verbatim. The one per-deployment field, the fail-open fallback cluster
address, is set structurally at runtime by ``resources.envoy_config``. Bump
CHART_VERSION and CHART_DIGEST together, then re-run the tests.
"""
from __future__ import annotations

import subprocess
import sys
import tempfile
from pathlib import Path

import yaml

CHART = "oci://ghcr.io/llm-d/charts/llm-d-router-standalone"
CHART_VERSION = "v1.0.0"
CHART_DIGEST = "sha256:c1d1af55382ef1097188d188070385c6de02b771f34681678e658a59e975024c"

OUT = Path(__file__).with_name("_chart_envoy.py")


def main() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        pull = subprocess.run(
            ["helm", "pull", CHART, "--version", CHART_VERSION, "--untar", "--untardir", tmp],
            check=True, capture_output=True, text=True,
        )
        if CHART_DIGEST not in pull.stdout + pull.stderr:
            print(f"chart digest mismatch: expected {CHART_DIGEST}\n{pull.stdout}{pull.stderr}", file=sys.stderr)
            return 1
        rendered = subprocess.run(
            ["helm", "template", "render", str(Path(tmp) / "llm-d-router-standalone"),
             "--namespace", "render",
             "--set", "router.modelServers.matchLabels.render=render",
             "--set", "router.modelServers.targetPorts[0].number=8000"],
            check=True, capture_output=True, text=True,
        ).stdout
    docs = [d for d in yaml.safe_load_all(rendered) if d]
    envoy = next(d for d in docs if d["kind"] == "ConfigMap" and d["metadata"]["name"] == "envoy")
    text = envoy["data"]["envoy.yaml"]
    yaml.safe_load(text)  # must parse
    OUT.write_text(
        '"""GENERATED by _regenerate.py; do not edit by hand.\n\n'
        f"Envoy sidecar config from {CHART} {CHART_VERSION}\n({CHART_DIGEST}).\n"
        '"""\n\n'
        f"CHART = {CHART!r}\n"
        f"CHART_VERSION = {CHART_VERSION!r}\n"
        f"CHART_DIGEST = {CHART_DIGEST!r}\n\n"
        f"ENVOY_YAML = {text!r}\n"
    )
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
